export const TOPICS: Topic[] = [...CORE_TOPICS, ...EXTRA_TOPICS];

export function getTopic(id: string) {
  return TOPICS.find((t) => t.id === id);
}

export function topicsByCategory(id: CategoryId) {
  return TOPICS.filter((t) => t.category === id);
}

export function searchTopics(q: string) {
  const t = q.trim().toLowerCase();
  if (!t) return TOPICS;
  return TOPICS.filter((topic) => {
    const hay = [
      topic.title,
      topic.tag,
      topic.meta,
      topic.num,
      ...topic.blocks.flatMap((b): string[] => {
        switch (b.type) {
          case "ul":
          case "ol":
            return b.items;
          case "table":
            return b.rows.flat();
          default:
            return [b.text];
        }
      }),
    ]
      .join(" ")
      .toLowerCase();
    return hay.includes(t);
  });
}
